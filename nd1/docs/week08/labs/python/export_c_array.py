#!/usr/bin/env python3
"""Convert model_int8.tflite into C source for the kws-inference firmware (like `xxd -i`).

    python export_c_array.py --model artifacts/model_int8.tflite \
        --out-dir ../firmware/kws-inference/main

Writes:
    model_data.cc   alignas(16) const unsigned char g_kws_model[] = { 0x1c, 0x00, ... };
    kws_labels.h    the label order (must match the model's output order)

The array is 16-byte aligned because TFLite Micro reads the FlatBuffer in place
from flash; misaligned model data can fault or be slow.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import kws_common as kc


def to_c_array(data: bytes, name: str, comment: str = "", per_line: int = 12) -> str:
    rows = []
    for i in range(0, len(data), per_line):
        rows.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) + ",")
    return (
        "// Generated by labs/python/export_c_array.py - do not edit by hand.\n"
        + "".join(f"// {line}\n" for line in comment.splitlines())
        + "\n// extern first: in C++ a namespace-scope const would otherwise have internal linkage.\n"
        f"extern const unsigned char {name}[];\nextern const unsigned int {name}_len;\n\n"
        f"alignas(16) const unsigned char {name}[] = {{\n" + "\n".join(rows) + "\n};\n"
        f"const unsigned int {name}_len = {len(data)};\n"
    )


def labels_header(labels, meta) -> str:
    items = ",\n".join(f'    "{lb}"' for lb in labels)
    q = meta.get("input_quant", {})
    return (
        "// Generated by labs/python/export_c_array.py - do not edit by hand.\n"
        "#pragma once\n\n"
        f"#define KWS_NUM_LABELS {len(labels)}\n"
        f"#define KWS_LABEL_SILENCE {labels.index(kc.SILENCE) if kc.SILENCE in labels else -1}\n"
        f"#define KWS_LABEL_UNKNOWN {labels.index(kc.UNKNOWN) if kc.UNKNOWN in labels else -1}\n\n"
        f"// Input quantization reported by the converter (the firmware reads the real values\n"
        f"// from the model at runtime; these are for reference): scale={q.get('scale')}, "
        f"zero_point={q.get('zero_point')}\n\n"
        "static const char *const kKwsLabels[KWS_NUM_LABELS] = {\n" + items + "\n};\n"
    )


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", type=Path, default=Path("artifacts/model_int8.tflite"))
    ap.add_argument("--out-dir", type=Path, default=Path("../firmware/kws-inference/main"))
    ap.add_argument("--name", default="g_kws_model")
    ap.add_argument("--comment", default="", help="extra comment line(s) for the top of model_data.cc")
    args = ap.parse_args(argv)

    data = args.model.read_bytes()
    meta_path = args.model.parent / "meta.json"
    meta = json.loads(meta_path.read_text()) if meta_path.exists() else {"labels": kc.LABELS}
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "model_data.cc").write_text(to_c_array(data, args.name, args.comment))
    (args.out_dir / "kws_labels.h").write_text(labels_header(meta["labels"], meta))
    print(f"Wrote {args.out_dir / 'model_data.cc'} ({len(data)} bytes) and {args.out_dir / 'kws_labels.h'}")
    if meta.get("int8_ops"):
        print("Ops used by the model (check kws_main.cc registers all of them):", meta["int8_ops"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
